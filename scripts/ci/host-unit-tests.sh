#!/bin/bash
# Builds and runs, natively on the host (macOS/Linux, clang++), the C++ unit tests that do not need Windows.
# What is built comes from tests/host/allowlist.txt (explicit, never guessed): "src" lines are the production files
# that compile on the host, "test" lines the unit-test files that run, "exclude" lines the ones that cannot, with a
# one-word reason. Every tests/unit/*_tests.cpp must appear in one of the last two, so a new test file cannot be forgotten.
# Exit 0 only if every registered test passes. Bash 3.2 compatible (macOS).
set -u
cd "$(dirname "$0")/../.." || exit 2

LIST="${HOST_TEST_ALLOWLIST:-tests/host/allowlist.txt}"
CXX="${CXX:-clang++}"
CXXFLAGS="-std=c++20 -Wall -Wextra -Isrc -Itests -Itests/host"
JOBS="$(sysctl -n hw.ncpu 2>/dev/null || nproc 2>/dev/null || echo 4)"
OUT="$(mktemp -d "${TMPDIR:-/tmp}/vf-host-tests.XXXXXX")" || exit 2
trap 'rm -rf "$OUT"' EXIT

list_kind() { awk -v k="$1" '$1 == k { print $2 }' "$LIST"; }
# The TestN functions defined by the allowlisted test files, in number order.
test_fns() { for f in $(list_kind test); do grep -oE '^void Test[0-9]+\(\)' "$f" | sed 's/^void //; s/()$//'; done | sort -t t -k 2 -n -u; }

# Every unit-test file must be classified.
for f in tests/unit/*_tests.cpp; do
    if ! awk -v f="$f" '($1 == "test" || $1 == "exclude") && $2 == f { found = 1 } END { exit !found }' "$LIST"; then
        echo "host-unit-tests: $f is not in $LIST (add a 'test' or 'exclude' line)" >&2
        exit 2
    fi
done

echo "== Rust core (host build)"
cargo build --release --locked --manifest-path rust/vegaflow-core/Cargo.toml >"$OUT/cargo.log" 2>&1 \
    || { cat "$OUT/cargo.log"; echo "host-unit-tests: cargo build failed" >&2; exit 1; }
RUST_LIB=rust/vegaflow-core/target/release/libvegaflow_core.a

# Generated registration table: one declaration and one table row per TestN of each allowlisted file.
{
    echo "// generated by scripts/ci/host-unit-tests.sh"
    test_fns | sed 's/.*/void &();/'
    echo "inline const std::pair<const char*, void (*)()> kHostTests[] = {"
    test_fns | sed 's/.*/    {"&", \&&},/'
    echo "};"
} >"$OUT/host_tests.inc"

echo "== Compile"
{
    for f in $(list_kind src) $(list_kind test); do echo "$f"; done
    echo tests/test_support.cpp
    # .cc, not .cpp: build.ps1 and build-cross.sh compile every tests/**/*.cpp into the Windows suite.
    echo tests/host/host_stubs.cc
    echo tests/host/host_main.cc
} | while read -r f; do echo "$f $OUT/$(echo "$f" | tr / _).o"; done >"$OUT/jobs.txt"
xargs -P "$JOBS" -L 1 sh -c '$0 '"$CXXFLAGS"' -I'"$OUT"' -c "$1" -o "$2" || { echo "compile failed: $1" >&2; exit 255; }' "$CXX" <"$OUT/jobs.txt" \
    || { echo "host-unit-tests: compile failed" >&2; exit 1; }

echo "== Link"
# Production code goes in an archive so the linker takes only the members a test needs: a src file that names
# Windows-only symbols is harmless until something really calls it, and then the link fails loudly.
# shellcheck disable=SC2046
ar rcs "$OUT/libsrc.a" $(awk '$1 ~ /^src\// { print $2 }' "$OUT/jobs.txt")
# shellcheck disable=SC2046
"$CXX" $(awk '$1 !~ /^src\// { print $2 }' "$OUT/jobs.txt") "$OUT/libsrc.a" "$RUST_LIB" -o "$OUT/host_tests" \
    || { echo "host-unit-tests: link failed" >&2; exit 1; }

echo "== Run"
"$OUT/host_tests"
status=$?

echo "== Excluded from the host run (see $LIST)"
awk '$1 == "exclude" { printf "  %-55s %s\n", $2, $3 }' "$LIST"
exit $status
