// The dxvk.conf VegaFlow writes starts with "# VegaFlow" (also true of 0.1.0); a UTF-8 BOM before it is tolerated.
static bool HasVegaFlowDxvkConf(const std::filesystem::path& dir) {
    std::ifstream conf(dir / L"dxvk.conf", std::ios::binary);
    std::string first;
    std::getline(conf, first);
    if (first.rfind("\xEF\xBB\xBF", 0) == 0) first.erase(0, 3);
    return first.rfind("# VegaFlow", 0) == 0;
}

bool DxvkManager::IsDxvkInstalled(const std::wstring& game_exe_path) {
    if (game_exe_path.empty()) return false;

    std::filesystem::path dir = ResolveGameDirectory(game_exe_path);
    if (dir.empty()) return false;

    std::error_code ec;
    if (!std::filesystem::exists(dir, ec) || !std::filesystem::is_directory(dir, ec)) {
        return false;
    }

    std::filesystem::path d3d11 = dir / L"d3d11.dll";
    std::filesystem::path dxgi = dir / L"dxgi.dll";
    if (!std::filesystem::exists(d3d11, ec) || !std::filesystem::exists(dxgi, ec)) return false;

    // A game may ship its own d3d11/dxgi DLLs: only the dxvk.conf we write last proves it was us.
    return HasVegaFlowDxvkConf(dir);
}

bool DxvkManager::RestoreUserDxvkConf(FileSystem& fs, const std::wstring& conf_path) {
    const std::wstring bak = conf_path + L".vegaflow.bak";
    if (!fs.Exists(bak)) {
        fs.Remove(conf_path, false); // the user had none: ours goes, as before
        return true;
    }
    if (!fs.Copy(bak, conf_path, true, false)) return false; // nothing is deleted: the user's copy stays in .vegaflow.bak
    fs.Remove(bak, false);
    return true;
}

bool DxvkManager::RemoveDxvk(
    const std::wstring& game_exe_path,
    bool dry_run,
    std::string* out_message) {

    if (dry_run) {
        if (!DryRunTargetOk(fs_, game_exe_path)) {
            if (out_message) *out_message = "Error: la carpeta del juego no existe o no se puede modificar (anti-cheat o fuera de lo permitido) [DRY-RUN]";
            return false;
        }
        if (out_message) {
            *out_message = "DXVK removido: El juego vuelve al driver DirectX 11 de Windows [DRY-RUN]";
        }
        return true;
    }

    std::filesystem::path dir = ResolveGameDirectory(game_exe_path);
    if (dir.empty()) {
        if (out_message) {
            *out_message = "Error: Ruta de juego inválida o vacía";
        }
        return false;
    }

    std::error_code ec;
    if (!std::filesystem::exists(dir, ec)) {
        if (out_message) {
            *out_message = "DXVK removido: El juego vuelve al driver DirectX 11 de Windows";
        }
        return true;
    }

    std::filesystem::path dstD3d11 = dir / L"d3d11.dll";
    std::filesystem::path dstDxgi = dir / L"dxgi.dll";
    std::filesystem::path confPath = dir / L"dxvk.conf";
    std::filesystem::path bakD3d11 = dir / L"d3d11.dll.original.bak";
    std::filesystem::path bakDxgi = dir / L"dxgi.dll.original.bak";

    // Only what VegaFlow put there is removed: a game that ships its own d3d11/dxgi (no marker, no backup) is left alone,
    // which also guards the --dxvk-remove command line.
    if (!HasVegaFlowDxvkConf(dir) && !std::filesystem::exists(bakD3d11, ec) && !std::filesystem::exists(bakDxgi, ec)) {
        if (out_message) *out_message = "VegaFlow no instaló DXVK en esta carpeta: no se tocó nada";
        return true;
    }

    // 1. DXVK's DLLs stay until step 3: the copy of the original replaces them, so a failed copy never leaves the game with none.
    const bool conf_back = RestoreUserDxvkConf(fs_, confPath.wstring());

    // 2. Delete logs generated by DXVK (*_d3d11.log, *_dxgi.log, dxvk.log)
    // Listed whole first (increment(ec) instead of ++, which throws); if the listing is cut by an error nothing is
    // deleted, the logs stay and the DLLs are still put back below.
    std::vector<std::wstring> logs;
    std::error_code list_ec;
    std::filesystem::directory_iterator it(dir, list_ec);
    for (const std::filesystem::directory_iterator end; !list_ec && it != end; it.increment(list_ec)) {
        std::error_code entry_ec;
        if (!it->is_regular_file(entry_ec)) continue;
        std::wstring fname = it->path().filename().wstring();
        if (EndsWithInsensitive(fname, L"_d3d11.log") ||
            EndsWithInsensitive(fname, L"_dxgi.log") ||
            EndsWithInsensitive(fname, L"dxvk.log")) {
            logs.push_back(it->path().wstring());
        }
    }
    if (!list_ec) {
        for (const auto& log : logs) fs_.Remove(log, false);
    }

    // 3. Put the game's own DLLs back. A backup is deleted only after its copy succeeded; a DLL that could not be
    // replaced or deleted (the game is open and has it loaded) makes the answer "no".
    bool dlls_ok = true;
    for (const auto& [bak, dst] : {std::pair{bakD3d11, dstD3d11}, std::pair{bakDxgi, dstDxgi}}) {
        if (std::filesystem::exists(bak, ec)) {
            if (fs_.Copy(bak.wstring(), dst.wstring(), true, false)) fs_.Remove(bak.wstring(), false);
            else dlls_ok = false;
        } else if (std::filesystem::exists(dst, ec)) {
            fs_.Remove(dst.wstring(), false); // the game had none of its own: ours goes
            if (std::filesystem::exists(dst, ec)) dlls_ok = false;
        }
    }
    if (!dlls_ok) {
        if (out_message) *out_message = "No se pudo quitar DXVK del todo: ¿el juego está abierto? Ciérralo y vuelve a intentarlo (tus DLL originales siguen guardadas como .original.bak)";
        return false;
    }

    if (out_message) {
        *out_message = "DXVK removido: El juego vuelve al driver DirectX 11 de Windows";
        if (!conf_back) *out_message += ". Tu dxvk.conf original no se pudo devolver: sigue como dxvk.conf.vegaflow.bak";
    }
    return true;
}

bool DxvkManager::ConfigureApuProfile(const std::filesystem::path& targetDir, const ApuOptimizationPolicy& policy, bool dryRun) {
    if (targetDir.empty()) {
        return false;
    }

    std::error_code ec;
    std::filesystem::path dir = targetDir;
    if (std::filesystem::exists(dir, ec) && std::filesystem::is_regular_file(dir, ec)) {
        dir = dir.parent_path();
    }

    if (!fs_.CanModifyGameDir(dir)) {
        return false;
    }

    if (dryRun) {
        return true;
    }

    std::filesystem::path confPath = dir / L"dxvk.conf";

    const std::vector<std::pair<std::string, std::string>> requiredSettings = {
        {"dxvk.enableAsync", "true"},
        {"dxvk.numCompilerThreads", std::to_string(policy.dxvk_compiler_threads)},
        {"dxvk.useEarlyDiscard", "true"},
        {"dxvk.pipelineLibrary", "true"},
        {"dxvk.enableGraphicsPipelineLibrary", "true"},
        {"dxvk.trackPipelineLifetime", "true"}
    };

    std::string newContent;
    if (!std::filesystem::exists(confPath, ec)) {
        std::ostringstream ss;
        ss << "# VegaFlow Universal - DXVK APU Optimization Profile\n";
        for (const auto& [key, val] : requiredSettings) {
            ss << key << " = " << val << "\n";
        }
        newContent = ss.str();
    } else {
        std::string existing;
        if (!fs_.Read(confPath.wstring(), existing)) return false;

        std::vector<std::string> lines;
        std::istringstream in(existing);
        std::string line;
        while (std::getline(in, line)) {
            if (!line.empty() && line.back() == '\r') line.pop_back();
            lines.push_back(line);
        }

        std::vector<bool> keyApplied(requiredSettings.size(), false);
        std::ostringstream ss;
        bool hasHeader = false;

        for (const auto& originalLine : lines) {
            std::string trimmed = originalLine;
            size_t start = trimmed.find_first_not_of(" \t\r\n");
            if (start == std::string::npos) {
                ss << originalLine << "\n";
                continue;
            }
            trimmed = trimmed.substr(start);

            if (trimmed.find("# VegaFlow Universal - DXVK APU Optimization Profile") != std::string::npos) {
                hasHeader = true;
            }

            bool matched = false;
            for (size_t i = 0; i < requiredSettings.size(); ++i) {
                const auto& key = requiredSettings[i].first;
                if (trimmed.rfind(key, 0) == 0) {
                    size_t klen = key.size();
                    if (klen == trimmed.size() || trimmed[klen] == ' ' || trimmed[klen] == '=' || trimmed[klen] == '\t') {
                        ss << key << " = " << requiredSettings[i].second << "\n";
                        keyApplied[i] = true;
                        matched = true;
                        break;
                    }
                }
            }

            if (!matched) {
                ss << originalLine << "\n";
            }
        }

        std::string updatedBody = ss.str();
        std::ostringstream finalOutput;
        if (!hasHeader) {
            finalOutput << "# VegaFlow Universal - DXVK APU Optimization Profile\n";
        }
        finalOutput << updatedBody;

        for (size_t i = 0; i < requiredSettings.size(); ++i) {
            if (!keyApplied[i]) {
                finalOutput << requiredSettings[i].first << " = " << requiredSettings[i].second << "\n";
            }
        }

        newContent = finalOutput.str();
    }

    return fs_.Write(confPath.wstring(), newContent, false);
}

bool DxvkManager::ValidateDxvkApuProfile(
    const std::filesystem::path& targetDir,
    bool& asyncEnabled,
    uint32_t& compilerThreads) {

    asyncEnabled = false;
    compilerThreads = 0;

    if (targetDir.empty()) {
        return false;
    }

    std::error_code ec;
    std::filesystem::path dir = targetDir;
    if (std::filesystem::exists(dir, ec) && std::filesystem::is_regular_file(dir, ec)) {
        dir = dir.parent_path();
    }

    std::filesystem::path confPath = dir / L"dxvk.conf";
    if (!std::filesystem::exists(confPath, ec) || !std::filesystem::is_regular_file(confPath, ec)) {
        return false;
    }

    std::string content;
    if (!fs_.Read(confPath.wstring(), content)) {
        return false;
    }

    if (content.empty()) {
        return false;
    }

    bool hasEarlyDiscard = false;
    bool hasPipelineLib = false;
    bool hasGpl = false;
    bool hasTrackLifetime = false;

    std::istringstream iss(content);
    std::string line;
    while (std::getline(iss, line)) {
        if (!line.empty() && line.back() == '\r') {
            line.pop_back();
        }
        size_t first = line.find_first_not_of(" \t");
        if (first == std::string::npos) continue;
        line = line.substr(first);
        if (line.empty() || line[0] == '#') continue;

        size_t eq = line.find('=');
        if (eq == std::string::npos) continue;

        std::string k = line.substr(0, eq);
        std::string v = line.substr(eq + 1);

        size_t kEnd = k.find_last_not_of(" \t");
        if (kEnd != std::string::npos) k = k.substr(0, kEnd + 1);

        size_t vStart = v.find_first_not_of(" \t");
        size_t vEnd = v.find_last_not_of(" \t");
        if (vStart != std::string::npos && vEnd != std::string::npos) {
            v = v.substr(vStart, vEnd - vStart + 1);
        } else {
            v = "";
        }

        std::string vLower = v;
        for (char& c : vLower) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));

        if (k == "dxvk.enableAsync") {
            if (vLower == "true" || vLower == "1") {
                asyncEnabled = true;
            }
        } else if (k == "dxvk.numCompilerThreads") {
            try {
                compilerThreads = static_cast<uint32_t>(std::stoul(v));
            } catch (...) {
                compilerThreads = 0;
            }
        } else if (k == "dxvk.useEarlyDiscard") {
            if (vLower == "true" || vLower == "1") {
                hasEarlyDiscard = true;
            }
        } else if (k == "dxvk.pipelineLibrary") {
            if (vLower == "true" || vLower == "1") {
                hasPipelineLib = true;
            }
        } else if (k == "dxvk.enableGraphicsPipelineLibrary") {
            if (vLower == "true" || vLower == "1") {
                hasGpl = true;
            }
        } else if (k == "dxvk.trackPipelineLifetime") {
            if (vLower == "true" || vLower == "1") {
                hasTrackLifetime = true;
            }
        }
    }

    return (asyncEnabled && compilerThreads >= 1 && compilerThreads <= 16 && hasEarlyDiscard && hasPipelineLib && hasGpl && hasTrackLifetime);
}

bool DxvkManager::RemoveApuProfile(const std::filesystem::path& targetDir, bool dryRun) {
    if (targetDir.empty()) {
        return false;
    }

    std::error_code ec;
    std::filesystem::path dir = targetDir;
    if (std::filesystem::exists(dir, ec) && std::filesystem::is_regular_file(dir, ec)) {
        dir = dir.parent_path();
    }

    if (!fs_.CanModifyGameDir(dir)) {
        return false;
    }

    if (dryRun) {
        return true;
    }

    std::filesystem::path confPath = dir / L"dxvk.conf";
    if (!std::filesystem::exists(confPath, ec)) {
        return true;
    }

    return fs_.Remove(confPath.wstring(), false);
}

