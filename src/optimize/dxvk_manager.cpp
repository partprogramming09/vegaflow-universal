bool EndsWithInsensitive(std::wstring_view str, std::wstring_view suffix) {
    if (suffix.size() > str.size()) return false;
    auto tail = str.substr(str.size() - suffix.size());
    return std::equal(
        tail.begin(), tail.end(),
        suffix.begin(), suffix.end(),
        [](wchar_t a, wchar_t b) {
            return std::towlower(a) == std::towlower(b);
        }
    );
}

std::filesystem::path ResolveGameDirectory(const std::wstring& game_exe_path) {
    if (game_exe_path.empty()) return {};
    std::error_code ec;
    std::filesystem::path p(game_exe_path);
    if (std::filesystem::is_directory(p, ec)) {
        return p;
    }
    return p.parent_path();
}

// A simulation checks what the real run would: the folder exists and may be changed (allowed, no anti-cheat).
bool DryRunTargetOk(FileSystem& fs, const std::wstring& game_exe_path) {
    const std::filesystem::path dir = ResolveGameDirectory(game_exe_path);
    std::error_code ec;
    return !dir.empty() && std::filesystem::is_directory(dir, ec) && fs.CanModifyGameDir(dir);
}

